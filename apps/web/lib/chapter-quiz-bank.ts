export function questionsFor(chapterId: string): QuizQuestion[] {
  return QUIZ_BANK.filter((x) => x.chapterId === chapterId);
}

/** Bank integrity: unique ids, 2–4 choices, answer in range, hints present. */
export function validateBank(bank: QuizQuestion[] = QUIZ_BANK): string[] {
  const issues: string[] = [];
  const seen = new Set<string>();
  for (const x of bank) {
    if (seen.has(x.id)) issues.push(`${x.id}: duplicate`);
    seen.add(x.id);
    if (!x.prompt?.trim()) issues.push(`${x.id}: missing prompt`);
    if (!Array.isArray(x.choices) || x.choices.length < 2 || x.choices.length > 4) {
      issues.push(`${x.id}: choices must be 2-4`);
    }
    if (!Number.isInteger(x.correct) || x.correct < 0 || x.correct >= (x.choices?.length ?? 0)) {
      issues.push(`${x.id}: correct out of range`);
    }
    if (!x.hint?.trim()) issues.push(`${x.id}: missing hint`);
  }
  return issues;
}
